#!/bin/sh
# tests/test_initd_path_has_opt_bin.sh — каждый наш init-скрипт обязан сам
# выставлять PATH с /opt/bin.
#
# Повод: 06.09.2026. NDM, cron и загрузка запускают init-скрипты с урезанным
# PATH, где инструментов Entware нет. Наши вызовы прикрыты `2>/dev/null`,
# поэтому отказ выходит МОЛЧАЛИВЫМ — не ошибка, а пустая строка.
#
# Чего это стоило. В S99zapret2 не было этой строки, и функция сверки
# планировщика не могла прочитать время файла через `stat` (он лежит в
# /opt/bin). Она писала «не читается время файлов — перезапуск пропущен» и
# уходила. Новый z2k-scheduler.sh ложился на диск, а в памяти оставался
# прежний процесс — до перезагрузки роутера. Из-за этого проба блока по
# объёму не запускалась НИ РАЗУ у людей, обновившихся до выпуска, где
# появился её десятиминутный повтор: файл приехал, запускать его было некому.
# В отчёте это выглядело как «механизм выключен».
#
# Проверено на роутере: с полным PATH `stat -c %Y` отдаёт время, с урезанным
# (/sbin:/usr/sbin:/bin:/usr/bin) — пусто.
# POSIX sh (busybox ash).

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PASS=0; FAIL=0
ok()  { PASS=$((PASS + 1)); printf '[PASS] %s\n' "$1"; }
bad() { FAIL=$((FAIL + 1)); printf '[FAIL] %s\n' "$1"; }

_n=0
for f in "$ROOT"/files/init.d/* "$ROOT"/files/S99zapret2.new; do
    [ -f "$f" ] || continue
    _n=$((_n + 1))
    if grep -qE '^export PATH=[^ ]*/opt/bin' "$f"; then
        ok "$(basename "$f"): PATH с /opt/bin выставляется"
    else
        bad "$(basename "$f"): нет своего PATH — инструменты Entware откажут молча"
    fi
done
[ "$_n" -gt 0 ] || bad "не нашёл ни одного init-скрипта — проверка ослепла"

# Сверка планировщика обязана падать В СТОРОНУ ПЕРЕЗАПУСКА. Пропуск здесь
# оставляет планировщик на старом коде навсегда, и притом молча; лишний
# перезапуск стоит долей секунды.
_sync=$(awk '/^_z2k_scheduler_sync\(\)/{f=1} f{print} f && /^\}/{exit}' "$ROOT/files/S99zapret2.new")
if [ -n "$_sync" ]; then
    if printf '%s\n' "$_sync" | grep -A2 -- '-z "\$_want"' | grep -q 'return 0'; then
        bad "при нечитаемом времени сверка пропускает перезапуск — планировщик застрянет на старом коде"
    else
        ok "при нечитаемом времени сверка всё равно перезапускает планировщик"
    fi
fi

echo
echo "PASSED: $PASS"
echo "FAILED: $FAIL"
[ "$FAIL" -eq 0 ]
